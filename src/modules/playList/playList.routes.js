const playListRouter = require('express').Router()
const addPlayList = require('./controller/addPlayList.controller')
const addFromApp = require('./controller/addFromApp.controller')
const updatePlayList = require('./controller/updatePlayList.controller')
const deletePlayList = require('./controller/deletePlayList.controller')
const checkPassword = require('./controller/checkPassword.controller')
const getPlayList = require('./controller/getPlayList.controller')
const activePlayList = require('./controller/activePlayList.controller')
const searchByMac = require('./controller/searchByMac.controller')
const getToApp = require('./controller/getToApp.controller')
const deleteFromApp = require('./controller/deleteFromApp.controller')
const { isUser } = require('../../middleware/auth')

playListRouter.post('/playList/add', isUser, addPlayList)
playListRouter.post('/playList/addFromApp', addFromApp)
playListRouter.put('/playList/update/:id', isUser, updatePlayList)
playListRouter.delete('/playList/delete/:id', isUser, deletePlayList)
playListRouter.post('/playList/checkPassword/:id', isUser, checkPassword)
playListRouter.get('/playList/get', isUser, getPlayList)
playListRouter.put('/playList/active/:id', activePlayList)
playListRouter.get('/playList/searchByMac', searchByMac)
playListRouter.get('/playList/getToApp', getToApp)
playListRouter.delete('/playList/deleteFromApp', deleteFromApp)

module.exports = playListRouter;