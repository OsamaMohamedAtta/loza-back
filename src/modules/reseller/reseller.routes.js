const resellerRouter = require('express').Router()
const login = require('./controller/login.controller')
const resellerInfo = require('./controller/resellerInfo.controller')
const updateReseller = require('./controller/updateReseller.controller')
const newSubscription = require('./controller/newSubscription.controller')
const getResellers = require('./controller/getReseller.controller')
const getSubscriptions = require('./controller/getSubscriptions.controller')
const addSubReseller = require('./controller/addSubReseller.controller')
const searchByMac = require('./controller/searchByMac.controller')
const getSubReseller = require('./controller/getSubReseller.controller')
const generateCode = require('./controller/generateCode.controller')
const getByCode = require('./controller/getByCode.controller')
